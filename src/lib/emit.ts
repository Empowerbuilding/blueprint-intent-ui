// Contract emission: builds intent.json (machine) + BRIEF.md (human/AI-readable,
// established format) from the structured intent data.

export type ContractDecision = {
  topic: string
  value: string
  source: string
  source_ref: string | null
  meeting_date: string | null
  superseded_by?: { value: string; meeting_date: string | null }[]
}

export type ContractRoom = {
  section_code: string
  name: string
  review_state: string
  area_sf?: number | null
  model_state?: Record<string, unknown>
  decisions: ContractDecision[]
  open_questions: { question: string; answer: string | null; default_if_unanswered: string | null; blocking: boolean }[]
  redline_notes: { note_type: string; text: string; source_ref: string | null }[]
  images: { storage_path: string; notes: string | null; tags: string[] }[]
}

export type Contract = {
  project: { name: string; client: string | null; emitted_version: number; emitted_at: string }
  rooms: ContractRoom[]
  unassigned_images: number
  parked_images: number
}

export function buildIntentJson(contract: Contract) {
  return contract
}

export function buildBriefMd(contract: Contract): string {
  const { project, rooms } = contract
  const lines: string[] = []

  lines.push(`# ${project.name} — D2 Intent Contract (BRIEF)`)
  lines.push('')
  lines.push(`_Generated by Design Intent UI v${project.emitted_version} at ${project.emitted_at}. `)
  lines.push(`This document is the authorization basis for the D2 work order. Every room below was `)
  lines.push(`explicitly reviewed (state shown per section); topics without a decision build to the `)
  lines.push(`runbook §4 defaults._`)
  lines.push('')

  const house = rooms.find((r) => r.section_code === 'HOUSE')
  const roomSections = rooms.filter((r) => r.section_code !== 'HOUSE').sort((a, b) =>
    a.section_code.localeCompare(b.section_code, undefined, { numeric: true })
  )

  const section = (r: ContractRoom) => {
    const label = r.section_code === 'HOUSE' ? 'House-Level (global)' : `${r.section_code}. ${r.name}`
    lines.push(`### ${label}`)
    const bits = [`Review state: **${r.review_state.replace('_', ' ')}**`]
    if (r.area_sf) bits.push(`${Math.round(r.area_sf)} SF`)
    const ms = Object.entries(r.model_state || {}).map(([k, v]) => `${k.replace(/_/g, ' ')}: ${v}`).join(', ')
    if (ms) bits.push(ms)
    lines.push(`_${bits.join(' · ')}_`)
    lines.push('')
    // every decision in the contract is active by construction; superseded_by
    // carries the history entries it replaced (rendered indented under it)
    if (r.decisions.length) {
      for (const d of r.decisions) {
        const src = d.source_ref ? ` (${d.source_ref})` : ''
        const date = d.meeting_date ? ` — ${d.meeting_date}` : ''
        lines.push(`- **${d.topic}:** ${d.value}${date}${src}`)
        for (const h of d.superseded_by || []) {
          lines.push(`  - ~~${h.value}~~ (${h.meeting_date || 'earlier'})`)
        }
      }
    } else {
      lines.push(`- _No room-specific decisions — builds entirely to runbook §4 defaults._`)
    }
    const unresolved = r.open_questions.filter((o) => !o.answer)
    if (unresolved.length) {
      lines.push('')
      for (const o of unresolved) {
        const def = o.default_if_unanswered ? ` → **DEFAULT:** ${o.default_if_unanswered}` : ''
        lines.push(`- ❓ ${o.question}${def}`)
      }
    }
    const answered = r.open_questions.filter((o) => o.answer)
    if (answered.length) {
      lines.push('')
      for (const o of answered) lines.push(`- ✅ ${o.question} → **${o.answer}**`)
    }
    if (r.redline_notes.length) {
      lines.push('')
      lines.push('_Redline notes (typed from D1 markup):_')
      for (const n of r.redline_notes) lines.push(`  - \`${n.note_type}\` ${n.text}${n.source_ref ? ` (${n.source_ref})` : ''}`)
    }
    if (r.images.length) {
      lines.push('')
      lines.push(`_Inspo (${r.images.length}):_ ` + r.images.map((i) => `${i.storage_path}${i.notes ? ` — ${i.notes}` : ''}`).join(' · '))
    }
    lines.push('')
  }

  if (house) section(house)
  for (const r of roomSections) section(r)

  if (contract.unassigned_images > 0) {
    lines.push(`> ⚠️ ${contract.unassigned_images} inspo image(s) still unassigned (parked: ${contract.parked_images}).`)
    lines.push('')
  }

  return lines.join('\n')
}
